export interface DevSeedOptions {
  /** Reference "now" (epoch millis). Defaults to Date.now(). Anchors all trends. */
  now?: number
  /** Base PRNG seed; each household gets its own offset from it. */
  seed?: number
}

/** Find a generated member row by display name, so an account can be linked to
 *  the person it belongs to. */
function findMember(dataset: DemoDataset, displayName: string): Record<string, unknown> | undefined {
  return (dataset.rows['member'] ?? []).find((m) => m['displayName'] === displayName)
}

/**
 * Wipe every table and insert the dev fixture: three households, five accounts
 * and a pending invitation, all locked behind {@link DEV_PASSWORD}. Meant to run
 * against ./data/dev (see scripts/seed-dev.ts), never the real database.
 * Returns a per-table row count.
 */
export async function seedDev(db: DB, opts: DevSeedOptions = {}): Promise<Record<string, number>> {
  const now = new Date(opts.now ?? Date.now())
  const baseSeed = opts.seed ?? 0x44455620 // "DEV "

  const datasets: DemoDataset[] = devHouseholds(now).map((spec, i) => ({
    householdId: spec.id,
    // A seed of its own per household: generated ids draw on the PRNG, so a
    // shared seed would mint the same ids twice and collide on insert.
    rows: buildDemoData({ now: now.getTime(), seed: baseSeed + i * 7919, household: spec }),
  }))
  const byHousehold = new Map(datasets.map((d) => [d.householdId, d]))

  // One hash for every account: they all share DEV_PASSWORD, and scrypt is
  // deliberately slow enough that hashing the same string five times is waste.
  const passwordHash = await hashPassword(DEV_PASSWORD)

  const users: Array<Record<string, unknown>> = []
  const memberships: Array<Record<string, unknown>> = []
  let ownerUserId = ''
  for (const spec of DEV_USERS) {
    const userId = newId()
    users.push({
      id: userId,
      username: spec.username,
      email: spec.email,
      displayName: spec.displayName,
      passwordHash,
      emailVerifiedAt: spec.emailVerified ? now : null,
      mfaSecret: null,
      mfaEnabledAt: null,
      mfaRecoveryCodes: null,
      mfaLastStep: null,
      onboardingDismissedAt: now, // past the first-run checklist
      createdAt: now,
      updatedAt: now,
    })
    for (const m of spec.memberships) {
      memberships.push({
        id: newId(),
        userId,
        householdId: m.householdId,
        role: m.role,
        invitedAt: now,
        acceptedAt: now,
        createdAt: now,
        updatedAt: now,
      })
      if (m.householdId === DEFAULT_HOUSEHOLD_ID && m.role === 'owner') ownerUserId = userId

      // Link the account to its budgeting member, where it has one.
      const dataset = byHousehold.get(m.householdId)
      const person = m.person && dataset ? findMember(dataset, m.person) : undefined
      if (person) person['userId'] = userId
    }
  }

  // A pending invitation to the primary household — the access screen lists it,
  // and /invite#DEV_INVITE_TOKEN walks the accept flow. `memberId` stays null:
  // `invitation` is inserted before `member`, so it can't reference one yet.
  const invitations = [
    {
      id: newId(),
      tokenHash: hashToken(DEV_INVITE_TOKEN),
      householdId: DEV_HOUSEHOLD_IDS.maple,
      role: 'member',
      email: 'newcomer@example.com',
      memberId: null,
      invitedByUserId: ownerUserId,
      createdAt: now,
      expiresAt: new Date(now.getTime() + 14 * 24 * 60 * 60 * 1000),
      acceptedAt: null,
    },
  ]

  // The identity rows ride along with the primary household's dataset. Each one
  // carries its own householdId where it has a column for it, so they land in the
  // right household rather than the dataset's.
  const primary = datasets[0]!
  primary.rows['user'] = users
  primary.rows['membership'] = memberships
  primary.rows['invitation'] = invitations

  const counts = await seedHouseholds(db, datasets)

  // instance_settings sits outside the wipe (it's instance-, not household-scoped),
  // so a re-seed would otherwise leave ownerUserId pointing at a deleted account.
  await setInstanceOwnerId(db, ownerUserId)
  await setAuthRequired(db, true)
  // Login lockouts are instance-level too — clear them so a re-seed is a clean slate.
  await db.delete(rateLimit)

  return counts
}

/** True if the dev fixture is already seeded (used to avoid re-seeding on every
 *  `tsx watch` restart). Checks every household, not just the primary one, so a
 *  database seeded with demo data is topped up rather than half-used. */
export async function hasDevData(db: DB): Promise<boolean> {
  const ids = Object.values(DEV_HOUSEHOLD_IDS)
  const rows = await db.select().from(household).where(inArray(household.id, ids))
  return rows.length === ids.length && rows.every((h) => h.setupCompletedAt != null)
}
