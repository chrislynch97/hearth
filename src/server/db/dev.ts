// ---------------------------------------------------------------------------
// Dev fixture
// ---------------------------------------------------------------------------
// The database `npm run dev:server` runs against (./data/dev): several fake
// households of deliberately different shapes, with real logins, so day-to-day
// development exercises the paths a single open household never reaches —
// household switching, roles, invites, a non-GBP currency, a non-monthly budget
// period, a one-person household.
//
// It is NOT the demo dataset: demo mode stays one open, password-less household
// (src/server/db/demo.ts), because a demo you have to log into is a bad demo.
// Both are generated by the same builder; this file only says who lives where.
//
// Every account shares DEV_PASSWORD — this database is disposable fake data and
// never leaves the machine. The seeder refuses any target that looks like the
// real database (scripts/demo-guard.ts).
// ---------------------------------------------------------------------------

